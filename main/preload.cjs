const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('monolith', {
  kernel: (op, args) => ipcRenderer.invoke('kernel', op, args),
  openFile: (opts) => ipcRenderer.invoke('file:open', opts),
  saveFile: (opts) => ipcRenderer.invoke('file:save', opts),
  writeFile: (path, text) => ipcRenderer.invoke('file:write', path, text),
  readFile: (path) => ipcRenderer.invoke('file:read', path),
  dwgToDxf: (path) => ipcRenderer.invoke('dwg:toDxf', path),
  dxfToDwg: (text, outPath) => ipcRenderer.invoke('dwg:fromDxf', text, outPath),
  newWindow: (kind, path) => ipcRenderer.invoke('win:new', kind, path),
  setTitle: (t) => ipcRenderer.send('win:title', t),
  setDirty: (d) => ipcRenderer.send('win:dirty', d),
  confirmClose: () => ipcRenderer.send('win:confirmClose'),
  recent: () => ipcRenderer.invoke('recent'),
  listFonts: () => ipcRenderer.invoke('fonts:list'),
  readFont: (p) => ipcRenderer.invoke('fonts:read', p),
  info: () => ipcRenderer.invoke('info'),
  pcInfo: (p) => ipcRenderer.invoke('pc:info', p),
  pcLoad: (args) => ipcRenderer.invoke('pc:load', args),
  fileExists: (p) => ipcRenderer.invoke('file:exists', p),
  onPcProgress: (fn) => { const h = (_e, p) => fn(p); ipcRenderer.on('pc-progress', h); return () => ipcRenderer.removeListener('pc-progress', h); },
  openExternal: (url) => ipcRenderer.invoke('openExternal', url),
  log: (lines) => ipcRenderer.send('log', lines),
  logCfg: (c) => ipcRenderer.invoke('log:cfg', c),
  logDir: () => ipcRenderer.invoke('log:dir'),
  setDarkMenu: (d) => ipcRenderer.send('ui:dark', d),
  setZoom: (f) => ipcRenderer.send('ui:zoom', f),
  onMenu: (fn) => ipcRenderer.on('menu', (_e, cmd, arg) => fn(cmd, arg)),
  onBeforeClose: (fn) => ipcRenderer.on('before-close', () => fn()),
});
