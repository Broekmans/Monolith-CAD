const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('monolith', {
  isTest: !!process.env.MONOLITH_TEST,
  optionsCfg: (o) => ipcRenderer.invoke('options:cfg', o),
  kernel: (op, args) => ipcRenderer.invoke('kernel', op, args),
  openFile: (opts) => ipcRenderer.invoke('file:open', opts),
  saveFile: (opts) => ipcRenderer.invoke('file:save', opts),
  writeFile: (path, text) => ipcRenderer.invoke('file:write', path, text),
  readFile: (path) => ipcRenderer.invoke('file:read', path),
  dwgToDxf: (path) => ipcRenderer.invoke('dwg:toDxf', path),
  dxfToDwg: (text, outPath) => ipcRenderer.invoke('dwg:fromDxf', text, outPath),
  dwgStatus: () => ipcRenderer.invoke('dwg:status'),
  dwgSetOda: (p) => ipcRenderer.invoke('dwg:setOda', p),
  newWindow: (kind, path) => ipcRenderer.invoke('win:new', kind, path),
  setTitle: (t) => ipcRenderer.send('win:title', t),
  setDirty: (d) => ipcRenderer.send('win:dirty', d),
  confirmClose: () => ipcRenderer.send('win:confirmClose'),
  recent: () => ipcRenderer.invoke('recent'),
  projects: () => ipcRenderer.invoke('projects:list'),
  createProject: (name) => ipcRenderer.invoke('projects:create', name),
  openProjectFolder: (dir) => ipcRenderer.invoke('projects:open-folder', dir),
  listFonts: () => ipcRenderer.invoke('fonts:list'),
  readFont: (p) => ipcRenderer.invoke('fonts:read', p),
  info: () => ipcRenderer.invoke('info'),
  pcInfo: (p) => ipcRenderer.invoke('pc:info', p),
  pcLoad: (args) => ipcRenderer.invoke('pc:load', args),
  cloudOpen: (p, req, opts) => ipcRenderer.invoke('cloud:open', p, req, opts),
  cloudRead: (id, names, want) => ipcRenderer.invoke('cloud:read', id, names, want),
  cloudPoint: (id, name, i) => ipcRenderer.invoke('cloud:point', id, name, i),
  cloudClose: (id) => ipcRenderer.invoke('cloud:close', id),
  cloudExport: (id, out, fmt, req, transform) => ipcRenderer.invoke('cloud:export', id, out, fmt, req, transform),
  cloudEdit: (spec, req) => ipcRenderer.invoke('cloud:edit', spec, req),
  cloudRegister: (spec, req) => ipcRenderer.invoke('cloud:register', spec, req),
  cloudOpenCache: (p) => ipcRenderer.invoke('cloud:openCache', p),
  cloudClean: (dir, keep) => ipcRenderer.invoke('cloud:clean', dir, keep),
  cloudDrawView: (spec) => ipcRenderer.invoke('cloud:drawView', spec),
  cloudSys: () => ipcRenderer.invoke('cloud:sysinfo'),
  onCloudProgress: (fn) => { const h = (_e, p) => fn(p); ipcRenderer.on('cloud-progress', h); return () => ipcRenderer.removeListener('cloud-progress', h); },
  fileExists: (p) => ipcRenderer.invoke('file:exists', p),
  onPcProgress: (fn) => { const h = (_e, p) => fn(p); ipcRenderer.on('pc-progress', h); return () => ipcRenderer.removeListener('pc-progress', h); },
  openExternal: (url) => ipcRenderer.invoke('openExternal', url),
  log: (lines) => ipcRenderer.send('log', lines),
  logDump: (n, t) => ipcRenderer.invoke('log:dump', n, t),
  draftStd: (s) => ipcRenderer.invoke('std:cfg', s),
  logCfg: (c) => ipcRenderer.invoke('log:cfg', c),
  logDir: () => ipcRenderer.invoke('log:dir'),
  setDarkMenu: (d) => ipcRenderer.send('ui:dark', d),
  setGridMenu: (g) => ipcRenderer.send('ui:grid', g),
  setIsoMenu: (g) => ipcRenderer.send('ui:iso', g),
  setViewportMenu: (v) => ipcRenderer.send('ui:viewport', v),
  setZoom: (f) => ipcRenderer.send('ui:zoom', f),
  onMenu: (fn) => ipcRenderer.on('menu', (_e, cmd, arg) => fn(cmd, arg)),
  onBeforeClose: (fn) => ipcRenderer.on('before-close', () => fn()),
});
