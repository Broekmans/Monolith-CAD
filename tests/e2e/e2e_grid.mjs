// 0.1.64: viewport grid (Top plane / sketch plane, 1-2-5 steps, per document + Interface menu) and colours
import { _electron as electron } from 'playwright-core';
const app = await electron.launch({ executablePath: './node_modules/.bin/electron', args: ['.', '--no-sandbox'], env: { ...process.env, MONOLITH_TEST: '1', MONOLITH_KIND: 'part' }, timeout: 60000 });
const win = await app.firstWindow();
const logs = [];
win.on('console', (m) => { if (/error/i.test(m.type()) && !/Security|WebGL|GPU stall|swiftshader/.test(m.text())) logs.push(`[${m.type()}] ${m.text()}`); });
win.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`));
const W = (ms) => win.waitForTimeout(ms);
await W(3500);
const shot = async (n) => { await W(500); await win.screenshot({ path: `tests/e2e/shots/grid-${n}.png` }); };
const st = () => win.evaluate(() => { const d = lithApp.doc, g = d.vp.grid; return { on: g.on, frame: g.frame ? g.frame.n.map((x) => Math.round(x)) : 'top', step: g.step.map((x) => +x.toPrecision(3)), doc: d.doc.grid ?? null }; });
console.log('1 default:', JSON.stringify(await st()));
await win.evaluate(() => { const vp = lithApp.doc.vp; vp.scale = 0.05; vp.requestRender(); }); await W(300);
const s1 = await st();
await win.evaluate(() => { const vp = lithApp.doc.vp; vp.scale = 2; vp.requestRender(); }); await W(300);
const s2 = await st();
console.log('2 zoom in / out steps:', JSON.stringify(s1.step), JSON.stringify(s2.step));
await win.evaluate(() => { const vp = lithApp.doc.vp; vp.scale = 0.25; vp.setView('iso', false); vp.requestRender(); }); await shot('iso-light');
// sketch on the Front plane: grid moves to the sketch plane
await win.locator('.tr-row:has-text("Front Plane")').click();
await win.locator('.cm-tab:has-text("Sketch")').click(); await win.locator('.cm-btn:has-text("Sketch")').first().click(); await W(800);
console.log('3 sketching on Front:', JSON.stringify(await st())); await shot('sketch');
await win.evaluate(() => lithApp.doc.exitSketch(false)); await W(300);
console.log('4 after sketch:', JSON.stringify(await st()));
await win.evaluate(() => lithApp.doc.toggleGrid()); await W(200);
console.log('5 doc toggle off:', JSON.stringify(await st()));
await win.evaluate(() => lithApp.onMenu('grid', true)); await W(200);
console.log('6 menu on (doc override cleared):', JSON.stringify(await st()));
await win.evaluate(() => lithApp.onMenu('grid', false)); await W(200);
console.log('7 menu off:', JSON.stringify(await st()), 'stored', await win.evaluate(() => localStorage.getItem('monolith.grid')));
console.log('  menu:', await app.evaluate(({ Menu }) => Menu.getApplicationMenu().items.find((i) => i.label.includes('Interface')).submenu.items.map((i) => i.label + (i.type === 'checkbox' ? '=' + i.checked : '')).join(' | ')));
await win.evaluate(() => lithApp.onMenu('grid', true)); await W(200);
// a 120 x 80 x 30 box on the Top plane: its bottom face lies on the grid plane (faces must win)
await win.locator('.tr-row:has-text("Top Plane")').click();
await win.locator('.cm-tab:has-text("Sketch")').click(); await win.locator('.cm-btn:has-text("Sketch")').first().click(); await W(700);
await win.evaluate(() => { const sk = lithApp.doc.sketcher; sk.vp.scale = 0.3; sk.vp.requestRender(); });
const P = async (x, y) => win.evaluate(([x, y]) => { const sk = lithApp.doc.sketcher; const r = sk.vp.el.getBoundingClientRect(); const s = sk.scr([x, y]); return [r.left + s[0], r.top + s[1]]; }, [x, y]);
const click = async (x, y) => { const [px, py] = await P(x, y); await win.mouse.move(px, py, { steps: 3 }); await win.mouse.down(); await win.mouse.up(); await W(120); };
await win.locator('.cm-btn:has-text("Center Rectangle")').click(); await click(0, 0); await click(60, 40); await win.keyboard.press('Escape');
await win.locator('.cc.ok').click(); await W(1500);
await win.locator('.cm-tab:has-text("Features")').click(); await win.locator('.cm-btn:has-text("Extruded Boss")').click(); await W(1500);
await win.locator('.pm-ok').click(); await W(2500);
await win.evaluate(() => { const vp = lithApp.doc.vp; vp.setView('iso', false); lithApp.doc.zoomFit(); vp.scale *= 2.2; vp.requestRender(); }); await shot('box-light');
await win.evaluate(() => lithApp.doc.vp.setView('front', false)); await W(200);
console.log('8 front view → grid on:', JSON.stringify(await st()));
await win.evaluate(() => lithApp.doc.vp.setView('iso', false));
await win.evaluate(() => lithApp.onMenu('theme', true)); await shot('iso-dark');
console.log('9 dark bg:', await win.evaluate(() => getComputedStyle(document.querySelector('.views')).backgroundImage.slice(0, 80)));
await win.evaluate(() => lithApp.onMenu('theme', false));
console.log('ERRORS:', logs.length ? logs.join('\n') : 'none');
await app.close();
