// 0.1.121: hovering a mate in the tree highlights its faces / edges in the view (hover colour, seen through the model);
// leaving the row clears it; selection highlight stays. Wouter's "Slide and rotation test" copy (needs ../scratch/motion/).
import fs from 'node:fs';
import { launch } from './common.mjs';
const errs = [];
const check = (name, ok, info = '') => { console.log(`${ok ? 'ok  ' : 'FAIL'} ${name} ${info}`); if (!ok) errs.push(name); };
const DIR = '/tmp/mh'; fs.rmSync(DIR, { recursive: true, force: true }); fs.mkdirSync(DIR, { recursive: true });
for (const f of fs.readdirSync('/home/claude/scratch/motion')) fs.copyFileSync(`/home/claude/scratch/motion/${f}`, `${DIR}/${f}`);
const T = await launch('assembly');
const { win, W, idle } = T;
await win.evaluate(async (p) => { await lithApp.open(p); await new Promise((r) => { const iv = setInterval(() => { const d = lithApp.doc; if (d && d.doc.kind === 'assembly' && d.doc.components.every((c) => c._part)) { clearInterval(iv); r(); } }, 50); }); }, `${DIR}/Slide and rotation test.lithasm`);
await W(1200); await idle();
const hl = () => win.evaluate(() => { const d = lithApp.doc, out = {}; for (const [id, v] of d.views) { const ch = v.hl.children; if (ch.length) out[id] = ch.map((o) => ({ col: '#' + o.material.color.getHexString(), dt: o.material.depthTest, type: o.isMesh ? 'face' : 'edge' })); } return out; });
const mates = await win.evaluate(() => lithApp.doc.doc.mates.map((m) => ({ id: m.id, name: m.name, a: m.a.comp, b: m.b.comp, ka: m.a.kind, kb: m.b.kind })));
const m1 = mates.find((m) => m.name === 'Concentric1');
const row = (id) => win.locator(`.tree .tr-row[data-item="mate:${id}"]`).first();
check('nothing highlighted at the start', Object.keys(await hl()).length === 0);
await row(m1.id).hover(); await W(300);
let h = await hl();
check('hover Concentric1 → both mated entities highlighted', h[m1.a]?.length >= 1 && h[m1.b]?.length >= 1, JSON.stringify(h));
const all = Object.values(h).flat();
check('hover colour, drawn through the model', all.every((x) => x.col === all[0].col && x.dt === false) && all[0].col !== '#1e90ff', JSON.stringify(all));
await T.shot('matehover-concentric1');
const w1 = mates.find((m) => m.name === 'Width1');
await row(w1.id).hover(); await W(300);
h = await hl();
check('hover Width1 → 4 faces (2 per component)', (h[w1.a]?.length || 0) + (h[w1.b]?.length || 0) === 4, JSON.stringify(Object.fromEntries(Object.entries(h).map(([k, v]) => [k, v.length]))));
await win.mouse.move(700, 450); await W(300); // into the view (empty area or a part)
await win.locator('.tree .tr-row[data-folder="mates"]').first().hover(); await W(300);
check('leaving the mate rows clears the highlight', Object.keys(await hl()).length === 0, JSON.stringify(await hl()));
await row(m1.id).click(); await W(300);
await win.locator('.tree .tr-row[data-folder="mates"]').first().hover(); await W(300);
h = await hl();
check('a selected mate stays highlighted (selection colour, not through)', Object.values(h).flat().every((x) => x.col === '#1e90ff') && Object.keys(h).length === 2, JSON.stringify(h));
await row(w1.id).hover(); await W(300);
h = await hl();
check('hover another mate while one is selected: both shown', Object.values(h).flat().some((x) => x.col === '#1e90ff') && Object.values(h).flat().some((x) => x.col !== '#1e90ff'));
await win.evaluate(() => lithApp.applyOptions({ asmMateHoverOpacity: 0.2 })); await row(m1.id).hover(); await W(300);
const op = await win.evaluate((id) => { const v = lithApp.doc.views.get(id); return v.hl.children.filter((o) => o.isMesh && o.material.depthTest === false).map((o) => o.material.opacity); }, m1.a);
check('Options: highlight strength applies', op.length && op.every((x) => Math.abs(x - 0.2) < 1e-9), op.join());
console.log(errs.length ? `FAILED ${errs.length}: ${errs.join(' | ')}` : 'ALL OK');
await T.app.close();
process.exit(errs.length ? 1 : 0);
