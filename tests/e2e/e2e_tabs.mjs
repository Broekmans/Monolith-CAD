import { _electron as electron } from 'playwright-core';
import fs from 'node:fs';
const app = await electron.launch({ executablePath: './node_modules/.bin/electron', args: ['.', '--no-sandbox'], env: { ...process.env, MONOLITH_TEST: '1', MONOLITH_KIND: 'part' }, timeout: 60000 });
const win = await app.firstWindow();
const logs = [];
win.on('console', (m) => { if (!/Security|WebGL|GPU stall|swiftshader|boot\]/.test(m.text())) logs.push(`[${m.type()}] ${m.text()}`); });
win.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}\n${e.stack}`));
await win.waitForTimeout(3500);
const shot = async (n) => { await win.waitForTimeout(500); await win.screenshot({ path: `tests/e2e/shots/${n}.png` }); };
const btn = (label) => win.locator(`.cm-btn:has-text("${label}")`).first().click();
const tab = (label) => win.locator(`.cm-tab:has-text("${label}")`).click();
const W = (ms) => win.waitForTimeout(ms);
process.on('exit', () => console.log(logs.join('\n')));
const idle = async () => { await W(300); await win.waitForFunction(() => !document.getElementById('busy').classList.contains('on'), null, { timeout: 30000 }); await W(200); };
// world point -> page
const WP = async (p) => win.evaluate((p) => { const vp = lithApp.doc.vp; const r = vp.el.getBoundingClientRect(); const s = vp.toScreen(p); return [r.left + s[0], r.top + s[1]]; }, p);
const tabs = () => win.evaluate(() => [...document.querySelectorAll('.dt')].map((d) => (d.classList.contains('on') ? '[' : '') + d.textContent.replace('×', '')).join(' | '));
console.log('start', await tabs());
await win.locator('.tr-row:has-text("Top Plane")').click();
await tab('Sketch'); await btn('Sketch'); await W(700);
await win.evaluate(() => lithApp.newDoc('part')); await W(1500);
console.log('after new', await tabs(), 'kind', await win.evaluate(() => document.body.dataset.kind), 'trees', await win.locator('.panel.tree').count());
await win.evaluate(() => lithApp.newDoc('plan')); await W(1500);
console.log('after plan', await tabs(), await win.evaluate(() => document.body.dataset.kind));
await win.keyboard.press('Control+Tab'); await W(300); console.log('ctrl-tab', await tabs(), 'welcome', await win.evaluate(() => getComputedStyle(document.querySelector('.welcome')).display));
await win.keyboard.press('Control+Tab'); await W(500);
console.log('tab1', await tabs(), 'sketcher', await win.evaluate(() => !!lithApp.doc.sketcher), 'corner', await win.evaluate(() => getComputedStyle(document.querySelector('.corner')).display), 'canvasW', await win.evaluate(() => lithApp.doc.vp.width));
await shot('tabs');
await win.keyboard.press('Control+Shift+Tab'); await W(300); console.log('back', await tabs());
await win.keyboard.press('Control+Tab'); await win.keyboard.press('Control+w'); await W(400); console.log('closed', await tabs());
await app.close();
